const sortArray = require("./912");

test("test sort an array", () => {
  expect(sortArray([5, 2, 3, 1])).toEqual([1, 2, 3, 5]);
  expect(sortArray([5, 1, 1, 2, 0, 0])).toEqual([0, 0, 1, 1, 2, 5]);
  expect(sortArray([1, 2, 3, 1, 2, 3, 2, 2, 3, 3, 1, 4, 5, 6, 2, 3])).toEqual([
    1, 1, 1, 2, 2, 2, 2, 2, 3, 3, 3, 3, 3, 4, 5, 6,
  ]);
  expect(sortArray([12, 5, 13, 4, 39, 9, 36, 38, 17, 27])).toEqual([
    4, 5, 9, 12, 13, 17, 27, 36, 38, 39,
  ]);
  expect(
    sortArray([
      9, 7, 1, 2, 7, 4, 2, 4, 6, 5, 3, 6, 7, 8, 0, 1, 12, 35, 11, 7, 6, 23,
    ])
  ).toEqual([
    0, 1, 1, 2, 2, 3, 4, 4, 5, 6, 6, 6, 7, 7, 7, 7, 8, 9, 11, 12, 23, 35,
  ]);
  expect(
    sortArray([
      15, 15, 2, 38, 20, 29, 14, 13, 12, 1, 20, 21, 4, 25, 5, 3, 19, 7, 14, 26,
    ])
  ).toEqual([
    1, 2, 3, 4, 5, 7, 12, 13, 14, 14, 15, 15, 19, 20, 20, 21, 25, 26, 29, 38,
  ]);
});
